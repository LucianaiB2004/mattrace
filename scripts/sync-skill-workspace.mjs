import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../skills/material-evidence-extractor/", import.meta.url);
const target = new URL("../app/domain/skill-files.generated.mjs", import.meta.url);
const checkOnly = process.argv.includes("--check");

async function filesBelow(url, prefix = "") {
  const entries = await readdir(url, { withFileTypes: true });
  const paths = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) paths.push(...await filesBelow(new URL(`${entry.name}/`, url), path));
    else paths.push(path);
  }
  return paths;
}

function metadata(path) {
  const category = path === "SKILL.md" || path.startsWith("agents/") || path.startsWith("references/") ? "contract" : path.startsWith("examples/") ? "example" : "code";
  const editable = path === "SKILL.md" || path === "agents/openai.yaml" || /^references\/(?:output-schema|coverage-and-comparability|evaluation-protocol|failure-cases)\.md$/.test(path);
  const extension = path.split(".").at(-1);
  const language = ({ md: "markdown", yaml: "yaml", json: "json", jsonl: "json", csv: "csv", mjs: "javascript" })[extension] ?? "text";
  return { category, editable, language };
}

const paths = await filesBelow(root);
const files = await Promise.all(paths.map(async (path) => ({ path, content: await readFile(new URL(path, root), "utf8"), ...metadata(path) })));
const generated = `// Generated by scripts/sync-skill-workspace.mjs. Do not edit by hand.\nexport const SKILL_FILE_SOURCES = ${JSON.stringify(files, null, 2)};\n`;

if (checkOnly) {
  let current = "";
  try { current = await readFile(target, "utf8"); } catch { /* reported below */ }
  if (current !== generated) {
    throw new Error(`Skill workspace mirror is stale. Run: node scripts/sync-skill-workspace.mjs\nTarget: ${fileURLToPath(target)}`);
  }
} else {
  await writeFile(target, generated, "utf8");
}
